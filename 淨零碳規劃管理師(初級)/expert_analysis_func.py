                "* 不確定性（Uncertainty）：指與測量結果相關的分散性參數，反映數據的懷疑程度。不確定性是由測量方法與假設天生決定的，『無法被消除』，只能透過更精準的儀器或方法來『降低』。\n"
                "這兩個詞在中文日常生活中可能被混用，但在查證標準中具有嚴格的學術界界線。"
